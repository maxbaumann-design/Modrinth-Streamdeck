/**
 * Generates every static image the plugin ships with, and the runtime icon module.
 *
 *   node scripts/generate-icons.mjs
 *
 * Outputs:
 *   com.maxbaumann.streamdeckbridge.sdPlugin/imgs/actions/<name>/icon.svg   (action list icon, monochrome)
 *   com.maxbaumann.streamdeckbridge.sdPlugin/imgs/actions/<name>/key.svg    (default key image)
 *   com.maxbaumann.streamdeckbridge.sdPlugin/imgs/plugin/category-icon.svg
 *   com.maxbaumann.streamdeckbridge.sdPlugin/imgs/plugin/marketplace.png (+@2x)
 *   ../fabric-mod/src/main/resources/assets/streamdeckbridge/icon.png
 *   src/ui/icons.generated.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ICONS, STROKE_ATTRS, iconSvg } from "./icons.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sdPlugin = path.join(root, "com.maxbaumann.streamdeckbridge.sdPlugin");
const imgs = path.join(sdPlugin, "imgs");

const ACTIONS = [
	"gamemode", "disconnect", "connect", "command", "perspective", "fullscreen", "screenshot", "hud",
	"debug", "pause", "volume", "hotbar", "ping", "fps", "coordinates", "status"
];

const KEY_BG = "#1b1f24";

function keySvg(name) {
	return `<svg xmlns="http://www.w3.org/2000/svg" width="144" height="144" viewBox="0 0 144 144">
<rect width="144" height="144" rx="18" fill="${KEY_BG}"/>
<g transform="translate(36 36) scale(3)" ${STROKE_ATTRS}>${ICONS[name]}</g>
</svg>
`;
}

/** Plugin / mod logo: an isometric grass block with a Stream Deck key grid on its front face. */
function logoSvg(size) {
	return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 256 256">
<defs>
  <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="#2b3138"/>
    <stop offset="1" stop-color="#15181c"/>
  </linearGradient>
</defs>
<rect width="256" height="256" rx="56" fill="url(#bg)"/>
<!-- grass block -->
<g transform="translate(128 132)">
  <polygon points="0,-78 68,-39 0,0 -68,-39" fill="#6abe4a"/>
  <polygon points="-68,-39 0,0 0,78 -68,39" fill="#7a5537"/>
  <polygon points="68,-39 0,0 0,78 68,39" fill="#5b3d27"/>
  <!-- grass overhang -->
  <polygon points="-68,-39 0,0 0,10 -68,-29" fill="#4f9c3a"/>
  <polygon points="68,-39 0,0 0,10 68,-29" fill="#3e7d2d"/>
  <!-- key grid on the right face -->
  <g fill="#f3f4f6" opacity="0.95">
    <polygon points="12,16 30,6 30,26 12,36"/>
    <polygon points="36,3 54,-7 54,13 36,23"/>
    <polygon points="12,42 30,32 30,52 12,62"/>
    <polygon points="36,29 54,19 54,39 36,49"/>
  </g>
</g>
</svg>`;
}

function categoryIconSvg() {
	// Monochrome grass-block outline with key grid, 28×28 canvas.
	return `<svg xmlns="http://www.w3.org/2000/svg" width="28" height="28" viewBox="0 0 24 24" ${STROKE_ATTRS}>
<path d="M12 2.5l8.5 4.75v9.5L12 21.5l-8.5-4.75v-9.5z"/>
<path d="M3.5 7.25L12 12l8.5-4.75"/>
<line x1="12" y1="12" x2="12" y2="21.5"/>
<path d="M13.8 13.6v2M16.4 12.2v2M13.8 17.3v2M16.4 15.9v2" stroke-width="1.6"/>
</svg>
`;
}

let chromiumPromise;
function loadChromium() {
	// Playwright is a dev-only dependency used to rasterise the logos; the generated PNGs are committed.
	chromiumPromise ??= (async () => {
		try {
			return (await import("playwright")).chromium;
		} catch {
			return createRequire(import.meta.url)("playwright").chromium;
		}
	})();
	return chromiumPromise;
}

async function renderPng(svg, size, outFile) {
	const chromium = await loadChromium();
	const browser = await chromium.launch();
	try {
		const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
		await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent">${svg}</body></html>`);
		await page.screenshot({ path: outFile, omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } });
	} finally {
		await browser.close();
	}
}

function write(file, content) {
	mkdirSync(path.dirname(file), { recursive: true });
	writeFileSync(file, content);
	console.log("wrote", path.relative(root, file));
}

// 1. Action icons + default key images
for (const name of ACTIONS) {
	write(path.join(imgs, "actions", name, "icon.svg"), iconSvg(name, 20) + "\n");
	write(path.join(imgs, "actions", name, "key.svg"), keySvg(name));
}

// 2. Category icon
write(path.join(imgs, "plugin", "category-icon.svg"), categoryIconSvg());

// 3. Runtime icon module
const ts = `// Generated by scripts/generate-icons.mjs — do not edit by hand.
/* eslint-disable */
export const ICONS: Record<string, string> = ${JSON.stringify(ICONS, null, "\t")};

export const STROKE_ATTRS = ${JSON.stringify(STROKE_ATTRS)};
`;
write(path.join(root, "src", "ui", "icons.generated.ts"), ts);

// 4. Raster logos (marketplace icon for Stream Deck, mod icon for Modrinth/Fabric)
const marketplace = path.join(imgs, "plugin");
await renderPng(logoSvg(256), 256, path.join(marketplace, "marketplace.png"));
await renderPng(logoSvg(512), 512, path.join(marketplace, "marketplace@2x.png"));
await renderPng(logoSvg(256), 256, path.join(root, "..", "fabric-mod", "src", "main", "resources", "assets", "streamdeckbridge", "icon.png"));
console.log("done");

// 5. Preview sheet for eyeballing all icons (not shipped)
if (process.argv.includes("--preview")) {
	const names = Object.keys(ICONS);
	const cols = 8, cell = 96;
	const rows = Math.ceil(names.length / cols);
	let sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="${cols * cell}" height="${rows * cell}" style="background:#333">`;
	names.forEach((n, i) => {
		const x = (i % cols) * cell, y = Math.floor(i / cols) * cell;
		sheet += `<g transform="translate(${x + 24} ${y + 12}) scale(2)" ${STROKE_ATTRS}>${ICONS[n]}</g><text x="${x + cell / 2}" y="${y + cell - 8}" fill="#ddd" font-size="11" text-anchor="middle" font-family="sans-serif">${n}</text>`;
	});
	sheet += "</svg>";
	const out = process.argv[process.argv.indexOf("--preview") + 1];
	await renderPng(sheet, Math.max(cols * cell, rows * cell), out);
	console.log("preview", out);
}
